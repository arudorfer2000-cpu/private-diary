// Turns the Expo web export into an installable, offline-capable, network-free web app.
// Usage: node scripts/pwa.mjs dist-web
import { createHash } from 'node:crypto';
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';

const dir = process.argv[2] ?? 'dist-web';
const THEME = '#0A1214';

const CSP = [
  "default-src 'none'",
  "script-src 'self' 'wasm-unsafe-eval'",
  "style-src 'self' 'unsafe-inline'",
  "img-src 'self' data: blob:",
  "font-src 'self' data:",
  "connect-src 'self'",
  "manifest-src 'self'",
  "worker-src 'self'",
  "frame-src about:",
  "object-src 'none'",
  "base-uri 'self'",
  "form-action 'none'",
].join('; ');

const walk = (d) => readdirSync(d).flatMap((n) => {
  const p = join(d, n);
  return statSync(p).isDirectory() ? walk(p) : [p];
});

// 0. headers file for hosts that read it (Netlify, Cloudflare Pages); other hosts rely on the meta tag below
writeFileSync(join(dir, '_headers'), `/*
  Content-Security-Policy: ${CSP}; frame-ancestors 'none'
  X-Content-Type-Options: nosniff
  Referrer-Policy: no-referrer
  X-Frame-Options: DENY
  Permissions-Policy: camera=(), microphone=(), geolocation=(self), payment=(), usb=()
/sw.js
  Cache-Control: no-cache
/index.html
  Cache-Control: no-cache
/manifest.webmanifest
  Cache-Control: no-cache
`);

// 1. manifest (all paths relative so the app works in a sub-folder)
writeFileSync(join(dir, 'manifest.webmanifest'), JSON.stringify({
  name: 'Private Diary',
  short_name: 'Diary',
  description: 'A private diary that stays on your device.',
  start_url: './',
  scope: './',
  display: 'standalone',
  orientation: 'portrait',
  background_color: THEME,
  theme_color: THEME,
  icons: [
    { src: 'icon-192.png', sizes: '192x192', type: 'image/png' },
    { src: 'icon-512.png', sizes: '512x512', type: 'image/png' },
    { src: 'icon-maskable-512.png', sizes: '512x512', type: 'image/png', purpose: 'maskable' },
  ],
}, null, 2));

// 2. index.html: relative links, manifest, Apple tags, CSP, offline registration
const indexPath = join(dir, 'index.html');
let html = readFileSync(indexPath, 'utf8');
const head = [
  `<meta http-equiv="Content-Security-Policy" content="${CSP}" />`,
  '<meta name="referrer" content="no-referrer" />',
  `<meta name="theme-color" content="${THEME}" />`,
  '<meta name="mobile-web-app-capable" content="yes" />',
  '<meta name="apple-mobile-web-app-capable" content="yes" />',
  '<meta name="apple-mobile-web-app-title" content="Diary" />',
  '<meta name="apple-mobile-web-app-status-bar-style" content="black-translucent" />',
  '<link rel="manifest" href="./manifest.webmanifest" />',
  '<link rel="apple-touch-icon" href="./apple-touch-icon.png" />',
].join('\n    ');
if (!html.includes('rel="manifest"')) html = html.replace('<meta charset="utf-8" />', '<meta charset="utf-8" />\n    ' + head);
html = html.replace('content="width=device-width, initial-scale=1, shrink-to-fit=no"', 'content="width=device-width, initial-scale=1, viewport-fit=cover, shrink-to-fit=no"');
if (!html.includes('register.js')) html = html.replace('</body>', '  <script src="./register.js" defer></script>\n</body>');
writeFileSync(indexPath, html);

// 3. service worker with the exact file list and a version made from the content
const files = walk(dir).map((p) => relative(dir, p).split(sep).join('/')).filter((f) => f !== 'sw.js' && f !== 'metadata.json' && f !== '_headers').sort();
const hash = createHash('sha256');
for (const f of files) hash.update(f).update(readFileSync(join(dir, f)));
const version = hash.digest('hex').slice(0, 12);
const sw = `// Offline cache for Private Diary. Generated by scripts/pwa.mjs. Version ${version}.
// It only serves files of this app from its own cache; it never contacts another site.
const CACHE = 'private-diary-${version}';
const FILES = ${JSON.stringify(['./', ...files], null, 1)};

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('private-diary-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== self.location.origin) return;
  event.respondWith(
    caches.match(req, { ignoreSearch: true }).then((hit) => hit || (req.mode === 'navigate' ? caches.match('./') : null) || fetch(req)),
  );
});
`;
writeFileSync(join(dir, 'sw.js'), sw);
console.log(`PWA ready: ${files.length} files cached, version ${version}`);
